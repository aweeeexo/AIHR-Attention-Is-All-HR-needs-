"""Регулярные выражения для ПДн. Общие для маскирования и для guard."""

from __future__ import annotations

import re

EMAIL = re.compile(r"[\w.+-]+@[\w-]+(?:\.[\w-]+)*\.[a-zA-Zа-яА-Я]{2,}")

# Российские номера: +7 / 8 и 10 цифр с любыми разделителями. Международные: +код и 8–12 цифр.
# Зарплаты («150 000 – 200 000») и даты («01.03.2019») под эти шаблоны не подходят.
PHONE = re.compile(
    r"(?<![\w+])(?:\+7|8)[\s\-‐–(]*\d{3}[\s\-‐–)]*\d{3}[\s\-‐–]*\d{2}[\s\-‐–]*\d{2}(?!\d)"
    r"|(?<![\w+])\+(?!7)\d{1,3}[\s\-(]*\d{2,4}[\s\-)]*\d{2,4}[\s\-]*\d{2,4}(?:[\s\-]*\d{2,4})?(?!\d)"
)

URL = re.compile(
    r"https?://[^\s<>«»\"')]+"
    r"|\bwww\.[^\s<>«»\"')]+"
    r"|\b(?:t\.me|telegram\.me|vk\.com|github\.com|gitlab\.com|linkedin\.com|instagram\.com"
    r"|facebook\.com|habr\.com/(?:ru/)?users|hh\.ru/resume|behance\.net|dribbble\.com)"
    r"/[^\s<>«»\"')]+",
    re.IGNORECASE,
)
# Ник в мессенджере: @ivan_petrov. Email к этому моменту уже заменён
HANDLE = re.compile(r"(?<![\w@.])@[A-Za-z][A-Za-z0-9_]{3,31}\b")

SNILS = re.compile(r"\b\d{3}-\d{3}-\d{3}[\s-]?\d{2}\b")
INN = re.compile(r"(?i)\bИНН\s*:?\s*\d{10,12}\b")
PASSPORT = re.compile(
    r"(?i)\bпаспорт\w*\s*(?:серия\s*)?:?\s*\d{2}\s?\d{2}\s*(?:№|номер)?\s*\d{6}\b"
)

_MONTHS = r"(?:января|февраля|марта|апреля|мая|июня|июля|августа|сентября|октября|ноября|декабря)"
_DATE = rf"(?:\d{{1,2}}[./]\d{{1,2}}[./]\d{{2,4}}|\d{{1,2}}\s+{_MONTHS}\s+\d{{4}}(?:\s*г\.?)?)"
BIRTHDATE = re.compile(
    rf"(?i)(дата\s+рождения|родил(?:ся|ась)|д\.\s?р\.|date\s+of\s+birth|born)\s*:?\s*({_DATE})"
)
AGE = re.compile(r"(?i)(возраст\s*:?\s*)(\d{2})(\s*(?:год|года|лет))?")
AGE_WITH_GENDER = re.compile(r"(?i)\b(мужчина|женщина)\s*,\s*\d{2}\s*(?:год|года|лет)\b")

_STREET = (
    r"(?:ул\.|улица|пр-т|просп\.|проспект|пер\.|переулок|ш\.|шоссе|б-р|бульвар|наб\.|набережная"
    r"|пл\.|площадь|мкр\.?|микрорайон)"
)
ADDRESS = re.compile(
    rf"(?i)(?:\b\d{{6}},?\s*)?(?:г\.\s*[А-ЯЁ][\w-]+,?\s*)?{_STREET}\s*[А-ЯЁA-Z0-9][^,;\n]{{1,40}}"
    rf"(?:,?\s*(?:д\.|дом)\s*\d+[\w/-]*)?(?:,?\s*(?:корп\.|к\.|стр\.)\s*\d+)?"
    rf"(?:,?\s*(?:кв\.|квартира)\s*\d+)?"
)

# Фразы о поле, семейном положении, детях и гражданстве: удаляем целиком (T02, шаг 1)
PERSONAL_PHRASES = re.compile(
    r"(?i)\b(?:мужчина|женщина|пол\s*:\s*\w+|(?:не\s+)?женат|(?:не\s+)?замужем|холост\w*|"
    r"в\s+браке|разведен\w*|вдов\w*|семейное\s+положение\s*:?[^,.;\n]*|"
    r"(?:есть|имею)\s+(?:дет\w+|ребен\w+|сын\w*|доч\w*)|дети\s*:?[^,.;\n]*|"
    r"гражданство\s*:?[^,.;\n]*)"
)

# Поля анкеты «Гражданство: …», «Семейное положение: …» — удаляем в любом месте резюме.
# Без двоеточия не трогаем: «работа с детьми» у педагога — это опыт, а не личные данные
PERSONAL_FIELDS = re.compile(
    r"(?i)\b(?:гражданство|семейное\s+положение|пол|дети|национальность|вероисповедание)"
    r"\s*:\s*[^,.;\n]*"
)

# Для guard: то, чего не должно быть в исходящем тексте ни в каком виде
GUARD_PATTERNS: dict[str, re.Pattern[str]] = {
    "email": EMAIL,
    "телефон": PHONE,
    "ссылка": URL,
    "СНИЛС": SNILS,
    "ИНН": INN,
    "паспорт": PASSPORT,
}
